"""Domain model representing an evaluation result for a query."""

from pydantic import BaseModel, Field

from ragdiag.diagnosis.models import DiagnosisResult
from ragdiag.models.chunk import RetrievedChunk


class EvaluationResult(BaseModel):
    """The outcome of running and diagnosing a single query sample through a RAG pipeline.

    Attributes:
        query_id: Identifier of the evaluated QuerySample.
        query: The evaluated query string.
        expected_chunk_ids: Ground truth relevant chunk IDs.
        retrieved_chunks: Chunks retrieved by the pipeline.
        generated_answer: The final text generated by the pipeline, if any.
        metrics: Computed quantitative evaluation metrics (e.g., recall, precision, faithfulness).
        diagnosis: Structured root-cause diagnostic findings.
        latency: Latency measurements in milliseconds (retrieval_ms, generation_ms, total_ms).
        status: Execution status (e.g., 'completed', 'failed').
        error: Error message string if pipeline execution or diagnosis encountered a failure.
    """

    query_id: str
    query: str
    expected_chunk_ids: list[str] = Field(default_factory=list)
    retrieved_chunks: list[RetrievedChunk] = Field(default_factory=list)
    generated_answer: str | None = None
    metrics: dict[str, object] = Field(default_factory=dict)
    diagnosis: DiagnosisResult | dict[str, object] = Field(default_factory=dict)
    latency: dict[str, float] = Field(default_factory=dict)
    status: str = "completed"
    error: str | None = None
    query_type: str | None = None
    judge_error: str | None = None
